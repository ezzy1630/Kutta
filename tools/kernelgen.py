#!/usr/bin/env python3
"""Generate backend entry points and typed host launchers from *.kern.h files.

Each kernel is written once:

    KUTTA_KERNEL void axpy(int i, KOut(float) y, KIn(float) x, float a) { ... }

and this script emits, into --out:

    kernels.hpp          KernelId enum + typed host launchers in kutta::kern
    kernels_host.cpp     launcher definitions (pack args, call Device::launch)
    kernels_cpu.cpp      CPU reference entry table
    kernels_cuda.cu      CUDA __global__ wrappers + launcher table
    kernels_metal.cpp    Metal source string (compiled at runtime) + entry names

Kernel names must be unique across all files. The first parameter must be
`int i`, the global index; generated wrappers do the bounds check.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys
from dataclasses import dataclass

KERNEL_RE = re.compile(r"KUTTA_KERNEL\s+void\s+(\w+)\s*\(")
BUF_RE = re.compile(r"^(KOut|KIn)\(\s*(float|int|uint)\s*\)\s+(\w+)$")
SCALAR_RE = re.compile(r"^(float|int|uint)\s+(\w+)$")

HOST_TYPE = {"float": "float", "int": "std::int32_t", "uint": "std::uint32_t"}


@dataclass(frozen=True)
class Param:
    kind: str  # "out", "in", "scalar"
    ctype: str  # float | int | uint
    name: str


@dataclass(frozen=True)
class Kernel:
    name: str
    params: tuple[Param, ...]
    source: pathlib.Path


def fail(msg: str) -> None:
    print(f"kernelgen: error: {msg}", file=sys.stderr)
    sys.exit(1)


def balanced_params(text: str, start: int, path: pathlib.Path) -> str:
    """Return the parameter list text from just after `(` to its matching `)`."""
    depth = 1
    for i in range(start, len(text)):
        if text[i] == "(":
            depth += 1
        elif text[i] == ")":
            depth -= 1
            if depth == 0:
                return text[start:i]
    fail(f"{path}: unbalanced parentheses in kernel signature")
    return ""


def parse_file(path: pathlib.Path) -> list[Kernel]:
    text = path.read_text()
    kernels = []
    for m in KERNEL_RE.finditer(text):
        name, raw = m.group(1), balanced_params(text, m.end(), path)
        parts = [" ".join(p.split()) for p in raw.split(",")]
        if not parts or parts[0] != "int i":
            fail(f"{path}: kernel {name}: first parameter must be `int i`")
        params = []
        for p in parts[1:]:
            if bm := BUF_RE.match(p):
                params.append(Param("out" if bm.group(1) == "KOut" else "in", bm.group(2), bm.group(3)))
            elif sm := SCALAR_RE.match(p):
                params.append(Param("scalar", sm.group(1), sm.group(2)))
            else:
                fail(f"{path}: kernel {name}: unsupported parameter `{p}`")
        for p in params:
            if p.name.startswith("kutta_"):
                fail(f"{path}: kernel {name}: parameter names starting with kutta_ are reserved")
        kernels.append(Kernel(name, tuple(params), path))
    return kernels


def include_path(path: pathlib.Path, src_root: pathlib.Path) -> str:
    return path.resolve().relative_to(src_root.resolve()).as_posix()


def gen_header(kernels: list[Kernel]) -> str:
    out = [
        "// Generated by tools/kernelgen.py. Do not edit.",
        "#pragma once",
        '#include "kutta/runtime/device.hpp"',
        "",
        "namespace kutta {",
        "",
        "enum class KernelId : std::uint16_t {",
    ]
    out += [f"  {k.name}," for k in kernels]
    out += [
        "};",
        f"inline constexpr std::size_t kKernelCount = {len(kernels)};",
        "const char* kernel_name(KernelId id);",
        "",
        "namespace kern {",
    ]
    for k in kernels:
        out.append(f"void {k.name}({host_signature(k)});")
    out += ["}  // namespace kern", "}  // namespace kutta", ""]
    return "\n".join(out)


def host_signature(k: Kernel) -> str:
    args = ["Device& kutta_dev", "std::size_t kutta_n"]
    for p in k.params:
        t = HOST_TYPE[p.ctype]
        if p.kind == "out":
            args.append(f"Buffer<{t}>& {p.name}")
        elif p.kind == "in":
            args.append(f"const Buffer<{t}>& {p.name}")
        else:
            args.append(f"{t} {p.name}")
    return ", ".join(args)


def gen_host(kernels: list[Kernel]) -> str:
    out = [
        "// Generated by tools/kernelgen.py. Do not edit.",
        '#include "kernels.hpp"',
        "",
        "namespace kutta {",
        "",
        "const char* kernel_name(KernelId id) {",
        "  static const char* const names[] = {",
    ]
    out += [f'      "{k.name}",' for k in kernels]
    out += [
        "  };",
        "  return names[static_cast<std::size_t>(id)];",
        "}",
        "",
        "namespace kern {",
    ]
    for k in kernels:
        packed = []
        for p in k.params:
            if p.kind == "scalar":
                packed.append(f"KernelArg::value<{HOST_TYPE[p.ctype]}>({p.name})")
            else:
                packed.append(f"KernelArg::buf({p.name})")
        out.append(f"void {k.name}({host_signature(k)}) {{")
        if packed:
            out.append(f"  const KernelArg kutta_args[] = {{{', '.join(packed)}}};")
            out.append(f"  kutta_dev.launch(KernelId::{k.name}, kutta_n, kutta_args);")
        else:
            out.append(f"  kutta_dev.launch(KernelId::{k.name}, kutta_n, {{}});")
        out.append("}")
    out += ["}  // namespace kern", "}  // namespace kutta", ""]
    return "\n".join(out)


def cpu_arg(p: Param, idx: int) -> str:
    if p.kind == "scalar":
        return f"kutta_args[{idx}].get<{HOST_TYPE[p.ctype]}>()"
    const = "const " if p.kind == "in" else ""
    ctype = "unsigned int" if p.ctype == "uint" else p.ctype
    return f"static_cast<{const}{ctype}*>(cpu_ptr(kutta_args[{idx}].buffer))"


def gen_cpu(kernels: list[Kernel], files: list[str]) -> str:
    out = [
        "// Generated by tools/kernelgen.py. Do not edit.",
        '#include "kutta/kernels/prelude.h"',
        '#include "kutta/runtime/cpu/cpu_kernel_table.hpp"',
        '#include "kernels.hpp"',
        "",
        "namespace kutta::ksrc {",
    ]
    out += [f'#include "{f}"' for f in files]
    out += ["}  // namespace kutta::ksrc", "", "namespace kutta {", "namespace {"]
    for k in kernels:
        out.append(f"void cpu_{k.name}(std::size_t kutta_begin, std::size_t kutta_end, const KernelArg* kutta_args) {{")
        for idx, p in enumerate(k.params):
            out.append(f"  auto {p.name} = {cpu_arg(p, idx)};")
        call = ", ".join(["static_cast<int>(kutta_i)"] + [p.name for p in k.params])
        out.append(f"  for (std::size_t kutta_i = kutta_begin; kutta_i < kutta_end; ++kutta_i) ksrc::{k.name}({call});")
        out.append("}")
    out += ["}  // namespace", "", "const CpuKernelFn cpu_kernel_table[] = {"]
    out += [f"    &cpu_{k.name}," for k in kernels]
    out += [
        "};",
        "static_assert(sizeof(cpu_kernel_table) / sizeof(cpu_kernel_table[0]) == kKernelCount);",
        "}  // namespace kutta",
        "",
    ]
    return "\n".join(out)


def cuda_param(p: Param) -> str:
    ctype = "unsigned int" if p.ctype == "uint" else p.ctype
    if p.kind == "scalar":
        return f"{ctype} {p.name}"
    const = "const " if p.kind == "in" else ""
    return f"{const}{ctype}* __restrict__ {p.name}"


def gen_cuda(kernels: list[Kernel], files: list[str]) -> str:
    out = [
        "// Generated by tools/kernelgen.py. Do not edit.",
        '#include "kutta/kernels/prelude.h"',
        '#include "kutta/runtime/cuda/cuda_kernel_table.hpp"',
        '#include "kernels.hpp"',
        "",
        "namespace kutta { namespace ksrc {",
    ]
    out += [f'#include "{f}"' for f in files]
    out += ["}}  // namespace kutta::ksrc", "", "namespace kutta {", "namespace {"]
    for k in kernels:
        params = ", ".join(["unsigned int kutta_n"] + [cuda_param(p) for p in k.params])
        call = ", ".join(["static_cast<int>(kutta_i)"] + [p.name for p in k.params])
        out.append(f"__global__ void g_{k.name}({params}) {{")
        out.append("  const unsigned int kutta_i = blockIdx.x * blockDim.x + threadIdx.x;")
        out.append(f"  if (kutta_i < kutta_n) ksrc::{k.name}({call});")
        out.append("}")
        args = ["static_cast<unsigned int>(kutta_n)"]
        for idx, p in enumerate(k.params):
            ctype = "unsigned int" if p.ctype == "uint" else p.ctype
            if p.kind == "scalar":
                args.append(f"kutta_args[{idx}].get<{HOST_TYPE[p.ctype]}>()")
            else:
                const = "const " if p.kind == "in" else ""
                args.append(f"static_cast<{const}{ctype}*>(cuda_ptr(kutta_args[{idx}].buffer))")
        out.append(f"void l_{k.name}(cudaStream_t kutta_s, std::size_t kutta_n, const KernelArg* kutta_args) {{")
        out.append("  const unsigned int kutta_blocks = static_cast<unsigned int>((kutta_n + kCudaBlock - 1) / kCudaBlock);")
        out.append(f"  g_{k.name}<<<kutta_blocks, kCudaBlock, 0, kutta_s>>>({', '.join(args)});")
        out.append("}")
    out += ["}  // namespace", "", "const CudaKernelFn cuda_kernel_table[] = {"]
    out += [f"    &l_{k.name}," for k in kernels]
    out += [
        "};",
        "static_assert(sizeof(cuda_kernel_table) / sizeof(cuda_kernel_table[0]) == kKernelCount);",
        "}  // namespace kutta",
        "",
    ]
    return "\n".join(out)


def metal_param(p: Param, idx: int) -> str:
    if p.kind == "scalar":
        return f"constant {p.ctype}& {p.name} [[buffer({idx})]]"
    const = "const " if p.kind == "in" else ""
    return f"{const}device {p.ctype}* {p.name} [[buffer({idx})]]"


def strip_includes(text: str) -> str:
    return "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("#include \"kutta/"))


def gen_metal(kernels: list[Kernel], paths: list[pathlib.Path], prelude: pathlib.Path) -> str:
    src = ["#define KUTTA_BACKEND_METAL 1", prelude.read_text(), "namespace ksrc {"]
    for p in paths:
        src.append(f"// ---- {p.name}")
        src.append(strip_includes(p.read_text()))
    src.append("}  // namespace ksrc")
    for k in kernels:
        n_idx = len(k.params)
        params = [metal_param(p, i) for i, p in enumerate(k.params)]
        params.append(f"constant uint& kutta_n [[buffer({n_idx})]]")
        params.append("uint kutta_gid [[thread_position_in_grid]]")
        call = ", ".join(["int(kutta_gid)"] + [p.name for p in k.params])
        src.append(f"kernel void kutta_{k.name}({', '.join(params)}) {{")
        src.append("  if (kutta_gid >= kutta_n) return;")
        src.append(f"  ksrc::{k.name}({call});")
        src.append("}")
    body = "\n".join(src) + "\n"
    if ")KUTTA_METAL\"" in body:
        fail("kernel source contains the raw-string terminator )KUTTA_METAL\"")
    out = [
        "// Generated by tools/kernelgen.py. Do not edit.",
        '#include "kutta/runtime/metal/metal_kernel_table.hpp"',
        '#include "kernels.hpp"',
        "",
        "namespace kutta {",
        "const char* const metal_kernel_source_parts[] = {",
    ]
    # Separate array elements, not adjacent literals: concatenation at compile
    # time would still exceed the compiler's 65,536-character literal limit.
    # Split UTF-8 bytes so the bound also holds if kernel comments use Unicode.
    chunk = ""
    size = 0
    for character in body:
        width = len(character.encode("utf-8"))
        if size + width > 60000:
            out.append(f'    R"KUTTA_METAL({chunk})KUTTA_METAL",')
            chunk, size = "", 0
        chunk += character
        size += width
    if chunk:
        out.append(f'    R"KUTTA_METAL({chunk})KUTTA_METAL",')
    out += [
        "};",
        "const std::size_t metal_kernel_source_part_count =",
        "    sizeof(metal_kernel_source_parts) / sizeof(metal_kernel_source_parts[0]);",
        "const char* const metal_kernel_entry[] = {",
    ]
    out += [f'    "kutta_{k.name}",' for k in kernels]
    out += [
        "};",
        "static_assert(sizeof(metal_kernel_entry) / sizeof(metal_kernel_entry[0]) == kKernelCount);",
        "}  // namespace kutta",
        "",
    ]
    return "\n".join(out)


def write_if_changed(path: pathlib.Path, text: str) -> None:
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src-root", required=True, type=pathlib.Path, help="directory containing kutta/")
    ap.add_argument("--out", required=True, type=pathlib.Path)
    ap.add_argument("files", nargs="+", type=pathlib.Path)
    args = ap.parse_args()

    paths = sorted(args.files, key=lambda p: p.as_posix())
    kernels: list[Kernel] = []
    for p in paths:
        kernels += parse_file(p)
    seen: dict[str, pathlib.Path] = {}
    for k in kernels:
        if k.name in seen:
            fail(f"kernel `{k.name}` defined in both {seen[k.name]} and {k.source}")
        seen[k.name] = k.source
    if not kernels:
        fail("no kernels found")

    includes = [include_path(p, args.src_root) for p in paths]
    prelude = args.src_root / "kutta" / "kernels" / "prelude.h"
    args.out.mkdir(parents=True, exist_ok=True)
    write_if_changed(args.out / "kernels.hpp", gen_header(kernels))
    write_if_changed(args.out / "kernels_host.cpp", gen_host(kernels))
    write_if_changed(args.out / "kernels_cpu.cpp", gen_cpu(kernels, includes))
    write_if_changed(args.out / "kernels_cuda.cu", gen_cuda(kernels, includes))
    write_if_changed(args.out / "kernels_metal.cpp", gen_metal(kernels, paths, prelude))


if __name__ == "__main__":
    main()
