#!/usr/bin/env python3
"""Integrate the first 40 mm of the 35-degree slant with clipped face polygons.

Reads only meshes generated by tools/fsae_aero/ahmed.py and own solver exports.
Face pressure is piecewise constant, as in the full-face force integral. This
removes the mesh-dependent band area of a whole-face centroid classification;
it does not improve pressure reconstruction or change the complete body load.
No restricted reference data is needed or exported.
"""
import argparse
import hashlib
import json
import pathlib
import re
import sys

import numpy as np
from scipy.spatial import cKDTree

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools/fsae_aero'))
import report  # noqa: E402


def polygon_geometry(p):
    """Area and area centroid of a convex planar polygon."""
    a = .5 * np.linalg.norm(np.cross(p[1:-1] - p[0], p[2:] - p[0]), axis=1)
    if a.sum() == 0:
        raise ValueError('degenerate polygon')
    return float(a.sum()), np.average((p[1:-1] + p[2:] + p[0]) / 3, axis=0, weights=a)


def clipped_area(p, x, *, keep_left=True):
    """Area after clipping against x<=cut (or x>=cut)."""
    out = []
    for a, b in zip(p, np.roll(p, -1, axis=0)):
        inside_a = a[0] <= x if keep_left else a[0] >= x
        inside_b = b[0] <= x if keep_left else b[0] >= x
        if inside_a:
            out.append(a)
        if inside_a != inside_b:
            out.append(a + (b - a) * ((x - a[0]) / (b[0] - a[0])))
    if len(out) < 3:
        return 0.
    q = np.array(out)
    return float(.5 * np.linalg.norm(np.cross(q[1:-1] - q[0], q[2:] - q[0]), axis=1).sum())


def body_polygons(mesh):
    """Read the nodes and named body face zone from our ASCII mesh writer."""
    with mesh.open() as f:
        if not next(f).startswith('(0 "fsae_aero ahmed '):
            raise ValueError('expected a generated Ahmed ASCII mesh')
        zones = [int(m[1]) for line in f
                 if (m := re.match(r'\(45 \((\d+) wall body\)', line))]
    if len(zones) != 1:
        raise ValueError('expected one named body wall zone')
    with mesh.open() as f:
        for line in f:
            if line.startswith('(10 (1 '):
                n = int(line.split()[3], 16)
                points = np.array([[float(v) for v in next(f).split()] for _ in range(n)])
                break
        else:
            raise ValueError('missing generated node block')
        for line in f:
            if line.startswith(f'(13 ({zones[0]:x} '):
                fields = line.split()
                n = int(fields[3], 16) - int(fields[2], 16) + 1
                faces = []
                for _ in range(n):
                    values = [int(v, 16) for v in next(f).split()]
                    faces.append(points[np.array(values[1:1 + values[0]]) - 1])
                return faces
    raise ValueError('missing body face block')


def summarize(path):
    receipt = json.loads((path / 'result.json').read_text())
    if receipt['result']['failure'] or receipt['mesh']['slant_deg'] != 35:
        raise ValueError('requires a nonfailed 35-degree run')
    command = receipt['command']
    mesh = ROOT / command[command.index('--mesh') + 1]
    area_ref = float(command[command.index('--area') + 1])
    digest = hashlib.sha256()
    with mesh.open('rb') as f:
        for block in iter(lambda: f.read(1 << 20), b''):
            digest.update(block)
    if digest.hexdigest() != receipt['mesh_sha256']:
        raise ValueError('mesh does not match the run receipt')
    phi = np.radians(35)
    xs = -.222 * np.cos(phi)
    walls = report.walls(path)
    walls = walls[report.regions(walls, 35)['slant']]
    down = np.array([np.cos(phi), 0, -np.sin(phi)])
    reverse = -np.column_stack([walls[k] for k in ('tau_x', 'tau_y', 'tau_z')]) @ down < 0
    tree = cKDTree(np.column_stack([walls[k] for k in ('x', 'y', 'z')]))
    total = leading = area = leading_area = error = 0.
    reverse_area = leading_reverse_area = 0.
    used = []
    for p in body_polygons(mesh):
        if np.max(np.abs(p[:, 2] - (.338 - (p[:, 0] - xs) * np.tan(phi)))) > 1e-8:
            continue
        a, centre = polygon_geometry(p)
        distance, j = tree.query(centre)
        error = max(error, distance)
        used.append(j)
        cut = clipped_area(p, xs + .04)
        area += a
        leading_area += cut
        if reverse[j]:
            reverse_area += a
            leading_reverse_area += cut
        pressure_normal = walls['cp'][j] * walls['nx'][j] / area_ref
        total += a * pressure_normal
        leading += cut * pressure_normal
    # These are geometry/identity checks, not adjustable CFD acceptance gates.
    if error > 1e-8 or len(used) != len(walls) or len(set(used)) != len(walls):
        raise ValueError('slant polygons do not match exported wall faces')
    if abs(area - .389 * .222) > 1e-8 or abs(leading_area - .389 * .04 / np.cos(phi)) > 1e-8:
        raise ValueError('clipped areas do not match the CAD slant')
    return dict(run=path.name, mesh_sha256=digest.hexdigest(), wall_identity_error_m=error,
                full_slant_area=area, leading_area=leading_area, total_pressure=total,
                leading_pressure=leading, remaining_pressure=total - leading,
                reversed_fraction=reverse_area / area,
                leading_reversed_fraction=leading_reverse_area / leading_area,
                remaining_reversed_fraction=(reverse_area - leading_reverse_area) / (area - leading_area))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('runs', nargs='+', type=pathlib.Path)
    ap.add_argument('--out', required=True, type=pathlib.Path)
    args = ap.parse_args()
    args.out.write_text(json.dumps([summarize(p) for p in args.runs], indent=2, allow_nan=False) + '\n')


if __name__ == '__main__':
    main()
