#pragma once

// Device runtime: buffers, kernel launch and reductions for one GPU (or the CPU
// reference backend). Kernels are written once in src/kutta/kernels/*.kern.h and
// tools/kernelgen.py generates the typed launch functions in kutta::kern.
//
// Ordering contract: launches, fills, copies and reductions on one Device execute
// in call order. Host-visible results (download, reductions) are complete when
// the call returns. Nothing else is guaranteed, so backends may batch freely.

#include <cstring>
#include <memory>
#include <span>
#include <string>
#include <type_traits>
#include <vector>

#include "kutta/core/types.hpp"

namespace kutta {

enum class Backend : std::uint8_t { Cpu, Metal, Cuda };

const char* backend_name(Backend b);

// Backend-owned allocation. Only backends look inside.
class BufferHandle {
 public:
  virtual ~BufferHandle() = default;
  virtual std::size_t bytes() const = 0;
};

class Device;

// Typed, move-only device array. Element types are restricted to what every
// kernel language can express identically: float, int32 and uint32.
template <class T>
class Buffer {
  static_assert(std::is_same_v<T, float> || std::is_same_v<T, std::int32_t> ||
                    std::is_same_v<T, std::uint32_t>,
                "device buffers hold float, int32 or uint32 only");

 public:
  Buffer() = default;
  Buffer(std::unique_ptr<BufferHandle> h, std::size_t n) : handle_(std::move(h)), size_(n) {}
  Buffer(Buffer&&) noexcept = default;
  Buffer& operator=(Buffer&&) noexcept = default;

  std::size_t size() const { return size_; }
  bool empty() const { return size_ == 0; }
  BufferHandle* handle() const { return handle_.get(); }

 private:
  std::unique_ptr<BufferHandle> handle_;
  std::size_t size_ = 0;
};

// One kernel argument as seen by a backend. Scalars travel by value (<= 8 bytes).
struct KernelArg {
  enum class Kind : std::uint8_t { Buffer, Scalar };
  Kind kind = Kind::Scalar;
  BufferHandle* buffer = nullptr;
  std::uint8_t scalar_size = 0;
  alignas(8) unsigned char scalar[8] = {};

  template <class T>
  static KernelArg buf(const Buffer<T>& b) {
    KernelArg a;
    a.kind = Kind::Buffer;
    a.buffer = b.handle();
    return a;
  }
  template <class T>
  static KernelArg value(T v) {
    static_assert(std::is_trivially_copyable_v<T> && sizeof(T) <= 8);
    KernelArg a;
    a.kind = Kind::Scalar;
    a.scalar_size = sizeof(T);
    std::memcpy(a.scalar, &v, sizeof(T));
    return a;
  }
  template <class T>
  T get() const {
    T v;
    std::memcpy(&v, scalar, sizeof(T));
    return v;
  }
};

// Generated by tools/kernelgen.py: enum class KernelId and the kernel table.
enum class KernelId : std::uint16_t;

class Device {
 public:
  virtual ~Device() = default;

  // Throws kutta::Error if the backend is not compiled in or no device exists.
  static std::unique_ptr<Device> create(Backend b);
  static std::vector<Backend> available();

  virtual Backend backend() const = 0;
  virtual std::string name() const = 0;  // e.g. "Apple M4 Pro"

  template <class T>
  Buffer<T> alloc(std::size_t n) {
    return Buffer<T>(alloc_bytes(n * sizeof(T)), n);
  }
  template <class T>
  void upload(Buffer<T>& dst, std::span<const T> src) {
    KUTTA_REQUIRE(src.size() == dst.size(), "upload size mismatch");
    upload_bytes(*dst.handle(), src.data(), src.size_bytes());
  }
  template <class T>
  void download(const Buffer<T>& src, std::span<T> dst) {
    KUTTA_REQUIRE(src.size() == dst.size(), "download size mismatch");
    download_bytes(*src.handle(), dst.data(), dst.size_bytes());
  }
  template <class T>
  Buffer<T> upload(std::span<const T> src) {
    Buffer<T> b = alloc<T>(src.size());
    upload(b, src);
    return b;
  }
  template <class T>
  std::vector<T> download(const Buffer<T>& src) {
    std::vector<T> v(src.size());
    download(src, std::span<T>(v));
    return v;
  }
  template <class T>
  void copy(Buffer<T>& dst, const Buffer<T>& src) {
    KUTTA_REQUIRE(src.size() == dst.size(), "copy size mismatch");
    copy_bytes(*dst.handle(), *src.handle(), src.size() * sizeof(T));
  }
  void fill(Buffer<float>& b, float v) { fill_bytes(*b.handle(), &v, sizeof v, b.size()); }
  void fill(Buffer<std::int32_t>& b, std::int32_t v) { fill_bytes(*b.handle(), &v, sizeof v, b.size()); }

  // Reductions accumulate in double (CPU, CUDA) or compensated float pairs
  // (Metal, which has no FP64) and return a double. Over the first n elements.
  virtual double sum(const Buffer<float>& x, std::size_t n) = 0;
  virtual double dot(const Buffer<float>& x, const Buffer<float>& y, std::size_t n) = 0;
  virtual double max_abs(const Buffer<float>& x, std::size_t n) = 0;

  // Runs kernel `id` for global indices [0, n). Called by generated kutta::kern code.
  virtual void launch(KernelId id, std::size_t n, std::span<const KernelArg> args) = 0;

  // Blocks until all queued work is complete. Needed only for timing.
  virtual void synchronize() = 0;

 protected:
  virtual std::unique_ptr<BufferHandle> alloc_bytes(std::size_t bytes) = 0;
  virtual void upload_bytes(BufferHandle& dst, const void* src, std::size_t bytes) = 0;
  virtual void download_bytes(const BufferHandle& src, void* dst, std::size_t bytes) = 0;
  virtual void copy_bytes(BufferHandle& dst, const BufferHandle& src, std::size_t bytes) = 0;
  virtual void fill_bytes(BufferHandle& dst, const void* value, std::size_t value_size,
                          std::size_t count) = 0;
};

}  // namespace kutta
